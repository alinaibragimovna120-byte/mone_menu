final _compiled = [
  for (final (from, to) in _fixes)
    (
      RegExp(
        // Слово целиком: перед и после — не буква (если фраза начинается/кончается буквой).
        '${RegExp('^[$_letters]').hasMatch(from) ? '(?<![$_letters])' : ''}'
        '${RegExp.escape(from)}'
        '${RegExp('[$_letters]\$').hasMatch(from) ? '(?![$_letters])' : ''}',
        caseSensitive: false,
      ),
      to,
    ),
];

/// Текст с исправленными опечатками (регистр как в оригинале).
String fixTypos(String s) {
  var out = s.replaceAll(RegExp(r'[ \t]{2,}'), ' ').trim(); // двойные пробелы из Excel
  for (final (re, to) in _compiled) {
    out = out.replaceAllMapped(re, (m) => _sameCase(m[0]!, to));
  }
  // «OМЛЕТ» с латинской O, точка в конце названия «(ХАЛЯЛЬ).»
  out = out.replaceAll(RegExp(r'^O(?=[А-ЯЁ])'), 'О').replaceAll(RegExp(r'\)\.$'), ')');
  return out;
}

String _sameCase(String original, String replacement) {
  final letters = original.replaceAll(RegExp('[^$_letters]'), '');
  if (letters.isNotEmpty && letters == letters.toUpperCase() && letters != letters.toLowerCase()) {
    return replacement.toUpperCase();
  }
  if (original.isNotEmpty && original[0] != original[0].toLowerCase()) {
    return replacement[0].toUpperCase() + replacement.substring(1);
  }
  return replacement;
}

/// Вариант с исправленными названиями ингредиентов и примечаниями.
CardVariant fixVariant(CardVariant v) => v.copyWith(
      title: fixTypos(v.title),
      ingredients: [for (final i in v.ingredients) i.copyWith(name: fixTypos(i.name))],
      notes: [for (final n in v.notes) fixTypos(n)],
    );

/// Название техкарты — с заглавной буквы («коктейли» → «Коктейли»).
String capFirst(String s) => s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);
